// Builds one icon sheet from public/icons/solar/*.svg: public/icons/solar-sprite.<hash>.svg
// (a <symbol id="s-<name>-<b|o>"> per glyph) and src/components/ui/solar-sprite-url.ts.
// The app loads the sheet once and draws every icon from it (no request per icon).
// Run after adding or changing a glyph:  node scripts/solar-sprite.mjs
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../public/icons/solar/", import.meta.url).pathname;
const out = new URL("../public/icons/", import.meta.url).pathname;
const symbols = readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => {
    const svg = readFileSync(join(dir, f), "utf8");
    const m = svg.match(/<g id="i">([\s\S]*)<\/g>\s*<\/svg>\s*$/);
    if (!m) throw new Error(`${f}: expected <g id="i">…</g>`);
    return `<symbol id="s-${f.replace(/\.svg$/, "")}" viewBox="0 0 24 24">${m[1]}</symbol>`;
  });
const sheet = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>`;
const hash = createHash("sha256").update(sheet).digest("hex").slice(0, 10);
for (const f of readdirSync(out)) if (/^solar-sprite\.[0-9a-f]+\.svg$/.test(f)) rmSync(join(out, f));
writeFileSync(join(out, `solar-sprite.${hash}.svg`), sheet);
writeFileSync(
  new URL("../src/components/ui/solar-sprite-url.ts", import.meta.url).pathname,
  `// Generated by scripts/solar-sprite.mjs — do not edit. The hash changes with the icons, so browsers keep it forever.\nexport const SOLAR_SPRITE_URL = "/icons/solar-sprite.${hash}.svg";\nexport const SOLAR_SPRITE_COUNT = ${symbols.length};\n`,
);
console.log(`solar-sprite.${hash}.svg: ${symbols.length} icons, ${sheet.length} bytes`);
